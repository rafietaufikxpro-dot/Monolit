uint16_t crc16(const uint8_t* data, size_t len) {
    uint16_t chk = 0xFFFF;
    for (size_t i = 0; i < len; i++)
        chk = (uint16_t)(CRC16_TABLE[(data[i] ^ chk) & 0xFF] ^ (chk >> 8));
    return (uint16_t)~chk;
}
