static inline uint32_t rotl(uint32_t x, int n) { return (x << n) | (x >> (32 - n)); }

static void md5Block(uint32_t st[4], const uint8_t* p) {
    uint32_t m[16];
    for (int i = 0; i < 16; i++)
        m[i] = (uint32_t)p[i*4] | (uint32_t)p[i*4+1] << 8 | (uint32_t)p[i*4+2] << 16 | (uint32_t)p[i*4+3] << 24;
    uint32_t a=st[0], b=st[1], c=st[2], d=st[3];
    for (int i = 0; i < 64; i++) {
        uint32_t f; int g;
        if (i < 16)      { f = (b & c) | (~b & d); g = i; }
        else if (i < 32) { f = (d & b) | (~d & c); g = (5*i + 1) & 15; }
        else if (i < 48) { f = b ^ c ^ d;          g = (3*i + 5) & 15; }
        else             { f = c ^ (b | ~d);       g = (7*i) & 15; }
        uint32_t tmp = d; d = c; c = b;
        b = b + rotl(a + f + MD5_K[i] + m[g], MD5_S[i]);
        a = tmp;
    }
    st[0]+=a; st[1]+=b; st[2]+=c; st[3]+=d;
}

void md5(const uint8_t* data, size_t len, uint8_t out[16]) {
    uint32_t st[4] = {0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476};
    size_t i = 0;
    for (; i + 64 <= len; i += 64) md5Block(st, data + i);
    uint8_t tail[128] = {0};
    size_t rem = len - i;
    memcpy(tail, data + i, rem);
    tail[rem] = 0x80;
    size_t tl = (rem < 56) ? 64 : 128;
    uint64_t bits = (uint64_t)len * 8;
    for (int k = 0; k < 8; k++) tail[tl - 8 + k] = (uint8_t)(bits >> (8*k));
    md5Block(st, tail);
    if (tl == 128) md5Block(st, tail + 64);
    for (int k = 0; k < 4; k++)
        for (int j = 0; j < 4; j++) out[k*4+j] = (uint8_t)(st[k] >> (8*j));
}

// ---------------- ccitt16 / crc16 (Gen 6/7 save block checksums) ----------------

uint16_t ccitt16(const uint8_t* data, size_t len) {
    uint16_t crc = 0xFFFF;
    for (size_t i = 0; i < len; i++) {
        crc ^= (uint16_t)(data[i] << 8);
        for (int j = 0; j < 8; j++) {
            if ((crc & 0x8000) != 0)
                crc = (uint16_t)((crc << 1) ^ 0x1021);
            else
                crc = (uint16_t)(crc << 1);
        }
    }
    return crc;
}

